package dev.zacx.dicta

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.util.Base64
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Authenticated encryption of a short secret, as a seam.
 *
 * The seam exists so [TokenStore]'s behaviour — that it round-trips, and that
 * the plaintext never reaches the preferences file — can be asserted in a JVM
 * unit test. `AndroidKeyStore` is a hardware-backed provider with no
 * Robolectric implementation, so the real [KeystoreCipher] is **not** covered
 * by the unit suite and is verified on the device instead. That is stated here
 * rather than left implicit, because "the token storage is tested" would
 * otherwise read as a stronger claim than the tests support.
 */
interface SecretCipher {
    /** @return an opaque, storable string. */
    fun encrypt(plaintext: String): String

    /** @return null when the blob is corrupt, truncated, or not ours. */
    fun decrypt(blob: String): String?
}

/**
 * AES-256/GCM with the key held in `AndroidKeyStore`.
 *
 * ## Why not `androidx.security:security-crypto`
 *
 * `EncryptedSharedPreferences` is the usual answer and was the operator's
 * first instinct, but it is a **runtime** AndroidX dependency and this APK
 * ships none — a previous change hand-rolled a `FileProvider` specifically to
 * keep that true, and the shipped dex contains zero `androidx` classes. The
 * guarantee that was actually wanted is "the token is encrypted at rest under
 * a key the app cannot export", and that is a `KeyGenParameterSpec` away with
 * framework APIs only. So this class provides the substance and skips the
 * coordinate. (Pinned by the dependency-free dex check in CI.)
 *
 * ## Properties of the key
 *
 * Generated on first use, non-exportable (the private material never leaves
 * the keystore — `getEncoded()` returns null), no user-authentication
 * requirement (dictation has to work on a locked-then-unlocked phone without
 * a biometric prompt mid-flow), and GCM with a randomised 12-byte IV
 * generated by the provider rather than by us.
 *
 * ## Failure behaviour: fail closed
 *
 * 🔴 If the keystore is unavailable the methods **throw**. They do not fall
 * back to storing the token in the clear, and they do not return the
 * plaintext unchanged — either of those would turn a crypto outage into a
 * silent plaintext-at-rest downgrade, which is precisely the thing this class
 * is here to prevent.
 */
class KeystoreCipher(
    private val alias: String = DEFAULT_ALIAS,
) : SecretCipher {

    override fun encrypt(plaintext: String): String {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, key())
        val iv = cipher.iv
        require(iv.size == IV_BYTES) { "unexpected GCM IV length ${iv.size}" }
        val ct = cipher.doFinal(plaintext.toByteArray(Charsets.UTF_8))
        return Base64.encodeToString(iv + ct, Base64.NO_WRAP)
    }

    override fun decrypt(blob: String): String? {
        val raw = try {
            Base64.decode(blob, Base64.NO_WRAP)
        } catch (_: IllegalArgumentException) {
            return null
        }
        if (raw.size <= IV_BYTES) return null
        return try {
            val cipher = Cipher.getInstance(TRANSFORMATION)
            cipher.init(
                Cipher.DECRYPT_MODE,
                key(),
                GCMParameterSpec(TAG_BITS, raw, 0, IV_BYTES),
            )
            val pt = cipher.doFinal(raw, IV_BYTES, raw.size - IV_BYTES)
            String(pt, Charsets.UTF_8)
        } catch (_: javax.crypto.AEADBadTagException) {
            // Wrong key or tampered ciphertext. Indistinguishable, and
            // deliberately so.
            null
        } catch (_: java.security.GeneralSecurityException) {
            null
        }
    }

    /** Fetches the existing key or creates it. */
    private fun key(): SecretKey {
        val ks = KeyStore.getInstance(PROVIDER).apply { load(null) }
        (ks.getEntry(alias, null) as? KeyStore.SecretKeyEntry)?.let {
            return it.secretKey
        }
        val generator = KeyGenerator.getInstance(
            KeyProperties.KEY_ALGORITHM_AES, PROVIDER
        )
        generator.init(
            KeyGenParameterSpec.Builder(
                alias,
                KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT,
            )
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(KEY_BITS)
                // Randomised IV per operation, enforced by the provider.
                .setRandomizedEncryptionRequired(true)
                .build()
        )
        return generator.generateKey()
    }

    companion object {
        const val DEFAULT_ALIAS: String = "dicta.stt.token.v1"
        private const val PROVIDER = "AndroidKeyStore"
        private const val TRANSFORMATION = "AES/GCM/NoPadding"
        private const val IV_BYTES = 12
        private const val TAG_BITS = 128
        private const val KEY_BITS = 256
    }
}
